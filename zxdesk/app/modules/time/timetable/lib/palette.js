'use strict';
/**
 * modules/timetable/lib/palette.js —— **课程配色**的唯一出处（服务端）
 *
 * 功能：`COURSE_COLORS` 是课程配色的调色板；`pickCourseColor(index)` 按「这门课在学期里的次序」
 *      取一个颜色 —— 新建课程与老数据兜底都走它。
 *
 * ⚠️ 为什么配色要有唯一出处：0.2.3 之前**没人给课程定颜色**，导入进来的课 `color` 全是空，
 *    前端只能统统回落到同一个默认蓝 —— 整张课表一片同色，「哪节是哪门课」得靠读字
 *    （「每个课程的颜色区分一下」）。颜色放在服务端一份，
 *    两端（电脑版 / 手机版）拿到的就是同一个值，不必各写一份调色板。
 *
 * ⚠️ 三条规矩：
 *    1. **用户/文件给了颜色就原样用**（`color` 非空一律不覆盖）；
 *    2. 兜底（老数据 `color` 为空）**只在返回给前端时算，不写库** —— 铁律 18「启动与迁移绝不改写用户数据」，
 *       颜色是显示属性，没有理由为了它去动老数据。
 *    3. ⭐ **颜色是课条的背景色、上面压白字**（实心色底、去掉左色条）——
 *       所以每个颜色都必须**实测**过「白字对比度 ≥ 4.5:1」（WCAG AA 正文标准），不是看着顺眼就收。
 *
 * ⚠️ 换色记录（**别退回亮色**）：0.2.3 首版调色板沿用了一批 Tailwind 500 档亮色
 *    （`#3b82f6` / `#f59e0b` / `#84cc16` / `#06b6d4` / `#10b981` / `#14b8a6`），它们当「左色条 + 浅底深字」
 *    没问题，但改成实心底压白字之后，实测对比度只有 **3.1~3.7:1**（琥珀 3.19、黄绿 3.09、
 *    天青 3.68、翠绿 3.77）—— 小字号直接糊成一片。现全部改为同色相 600/700 档，见下方逐色实测值。
 *    ⚠️ 顺序也**不要为了「好看」随意重排** —— 顺序即分配顺序，重排会让所有课程的默认色跟着变；
 *    当前顺序刻意让**相邻两门课色相差得开**（连续取色时才分得清）。
 *
 * @author zx
 * @date   2026-09-12
 * @since 0.8.13
 * 相关：docs/公共/架构文档/06-课表.md
 */

/**
 * 课程调色板：12 个色相分得开的颜色，**每一个都实测过「白字压上去 ≥ 4.5:1」**（数字即实测值）。
 * @type {Array.<string>}
 */
const COURSE_COLORS = [
  '#2563eb', // 蓝    5.17
  '#b91c1c', // 红    6.47
  '#047857', // 翠绿  5.48
  '#b45309', // 琥珀  5.02
  '#7c3aed', // 紫    5.70
  '#0f766e', // 青    5.47
  '#be185d', // 玫红  6.04
  '#4d7c0f', // 黄绿  4.99
  '#4338ca', // 靛    7.90
  '#c2410c', // 橙    5.18
  '#0e7490', // 天青  5.36
  '#7e22ce', // 亮紫  6.98
];

/**
 * 功能：按序号取一个课程颜色（负数、非数字、超大序号都能安全落到合法下标）。
 * @param {number} index - 「这门课在学期里的次序」，从 0 起
 * @returns {string} `#RRGGBB` 形式的颜色
 */
function pickCourseColor(index) {
  const n = Number(index);
  const i = Number.isFinite(n) ? Math.floor(n) : 0;
  const len = COURSE_COLORS.length;
  return COURSE_COLORS[((i % len) + len) % len];
}

module.exports = {
  COURSE_COLORS,
  pickCourseColor,
};
