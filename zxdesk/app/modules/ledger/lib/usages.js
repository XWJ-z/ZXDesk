'use strict';
/**
 * modules/ledger/lib/usages.js —— 内置「按账户用途」的**那 7 个字段**（全项目唯一出处）
 *
 * 功能：给出内置用途的 seed 清单（键 / 显示名 / 是否锁定）与两个上限常量。
 *
 * ⭐⭐ 为什么用途要存**稳定键 `gkey`**（「用户可以给这些用途分类字段重命名」）：
 *    账户的归属（`ledger_view_tags.tag`）存的是**键**而不是名字 ⇒ 改一次名，
 *    所有归在那组下面的账户**自动跟着新名走**。若存名字，改名的表现是
 *    「那一组的所有账户静默掉到『其它』」—— 不报错、金额也照旧，只是分组全乱。
 *    ⇒ `u1..u7` 一经生成**永不变**（与 `lib/kinds.js` 里「`kind` 键不许改名」同一条纪律）。
 *
 * ⭐ 「其它」是**兜底组**（`locked = true`）：没归类的账户在界面上落在这里。
 *    它**不可删**（删了那些账户在「按账户用途」这一屏就**无处可去** ——
 *    金额还在总数里、屏幕上却找不到它们），也**不许被拖走**（永远最后）。
 *    ⚠️ 它的**名字可以改**（与其余 6 个一样）—— 改的是显示名，不是它的身份。
 *
 * ⚠️ `USAGE_MAX` 是**产品决定**，不是技术限制：一行放得下多少组标题
 *    （与 `lib/views.js` 的 `VIEW_MAX` 同一条理由）。
 *
 * @author zx
 * @date   2026-09-22
 * @since  0.8.0
 * 相关：docs/公共/架构文档/23-记账.md、docs/公共/开发方案/20-记账1期-资产管家.md
 */

/**
 * 内置用途的 seed 清单 —— **顺序即初始顺序**（`ledger_groups.sort_order` 取数组下标）。
 *
 * 说明：⚠️ 只在新账号（或老账号第一次被用到）时用来灌种子；用户之后可以改名 / 增删 / 拖排序。
 * @type {Array.<{gkey: string, name: string, locked?: boolean}>}
 */
const USAGE_SEED = [
  { gkey: 'u1', name: '日用' },
  { gkey: 'u2', name: '借入' },
  { gkey: 'u3', name: '中转站' },
  { gkey: 'u4', name: '借出' },
  { gkey: 'u5', name: '创业' },
  { gkey: 'u6', name: '攒钱' },
  // ⭐ 兜底组：不可删、不许被拖走（永远排在最后）；⚠️ 但名字可以改
  { gkey: 'u7', name: '其它', locked: true },
];

/** 「其它」的键 —— 「没归类」的落点（业务层要认它，⛔ 别在别处再硬编码一个字符串） */
const USAGE_OTHER_KEY = 'u7';

/** 一个人最多能有多少个用途字段（含「其它」；一行放得下多少组标题） */
const USAGE_MAX = 12;

module.exports = { USAGE_SEED, USAGE_OTHER_KEY, USAGE_MAX };
